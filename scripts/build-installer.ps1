# Builds dist\<product>-setup-<version>.exe
#   powershell -File scripts\build-installer.ps1            full build (cargo release + extension + installer)
#   powershell -File scripts\build-installer.ps1 -SkipBuild reuse the existing target\release binaries
# Needs Inno Setup 6 (https://jrsoftware.org/isinfo.php). Name, colour, company, GUID: brand\brand.toml.
param([switch]$SkipBuild)
$ErrorActionPreference = 'Stop'
$root = Split-Path -Parent $PSScriptRoot
Set-Location $root

$brand = Get-Content brand\brand.toml -Raw
function Get-Brand($key, [switch]$Optional) {
  if ($brand -match "(?m)^$key\s*=\s*`"([^`"]*)`"") { return $Matches[1] }
  if ($Optional) { return '' }
  throw "brand.toml has no $key"
}
$name = Get-Brand 'name'; $product = Get-Brand 'product_id'; $company = Get-Brand 'company'
$homepage = Get-Brand 'homepage'; $guid = Get-Brand 'app_guid'; $store = Get-Brand 'store_url' -Optional
if ($product -notmatch '^[a-z0-9]+$') { throw "product_id must be lower-case letters and digits (got '$product')" }
if ($guid -notmatch '^[0-9A-Fa-f-]{36}$') { throw "app_guid is not a GUID: $guid" }
if ((Get-Content host\Cargo.toml -Raw) -notmatch '(?m)^version\s*=\s*"([0-9]+(\.[0-9]+){0,3})"') { throw 'cannot read the version from host\Cargo.toml' }
$version = $Matches[1]

if (-not $SkipBuild) {
  # a running copy would keep the .exe files locked
  & "$root\target\release\dmhost.exe" quit 2>$null
  cargo build --release
  if ($LASTEXITCODE -ne 0) { throw 'cargo build failed' }
}
foreach ($f in 'dmd.exe', 'dmhost.exe') { if (-not (Test-Path "target\release\$f")) { throw "missing target\release\$f (run without -SkipBuild)" } }
foreach ($f in 'app.ico', 'wizard-large.bmp', 'wizard-large@2x.bmp', 'wizard-small.bmp', 'wizard-small@2x.bmp') { if (-not (Test-Path "brand\assets\$f")) { throw "missing brand\assets\$f" } }

& powershell -NoProfile -File "$root\scripts\package-extension.ps1"
if ($LASTEXITCODE -ne 0) { throw 'extension packaging failed' }

$q = { param($s) $s.Replace('"', '""') }
$lines = @(
  "; Generated by scripts\build-installer.ps1 from brand\brand.toml. Do not edit.",
  "#define BrandName `"$(& $q $name)`"", "#define ProductId `"$product`"", "#define Company `"$(& $q $company)`"",
  "#define Homepage `"$(& $q $homepage)`"", "#define AppGuid `"$guid`"", "#define Version `"$version`"", "#define StoreUrl `"$(& $q $store)`""
)
New-Item -ItemType Directory -Force dist | Out-Null
Set-Content -Path dist\brand.iss -Value $lines -Encoding UTF8

$iscc = @("$env:LOCALAPPDATA\Programs\Inno Setup 6\ISCC.exe", "${env:ProgramFiles(x86)}\Inno Setup 6\ISCC.exe", "$env:ProgramFiles\Inno Setup 6\ISCC.exe") | Where-Object { Test-Path $_ } | Select-Object -First 1
if (-not $iscc) { throw 'Inno Setup 6 not found. Install it from https://jrsoftware.org/isdl.php' }
& $iscc /Qp installer\setup.iss
if ($LASTEXITCODE -ne 0) { throw 'Inno Setup failed' }

$out = Get-Item "dist\$product-setup-$version.exe"
$hash = (Get-FileHash $out.FullName -Algorithm SHA256).Hash.ToLower()
Write-Host ("{0}  {1:N1} MB  sha256 {2}" -f $out.FullName, ($out.Length / 1MB), $hash)
