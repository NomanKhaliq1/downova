# Builds dist/extension from extension/ with the brand applied.
#   powershell -File scripts/package-extension.ps1
# Reads brand/brand.toml (name, product_id) and host/Cargo.toml (version: extension and host must match).
$ErrorActionPreference = 'Stop'
$root = Split-Path -Parent $PSScriptRoot
$brandToml = Get-Content (Join-Path $root 'brand\brand.toml') -Raw
function Get-Brand($key) {
  if ($brandToml -match "(?m)^$key\s*=\s*`"([^`"]*)`"") { return $Matches[1] }
  throw "brand.toml has no $key"
}
$name = Get-Brand 'name'
$product = Get-Brand 'product_id'
if ($product -notmatch '^[a-z0-9]+$') { throw "product_id must be lower-case letters and digits only (got '$product')" }
$cargo = Get-Content (Join-Path $root 'host\Cargo.toml') -Raw
if ($cargo -notmatch '(?m)^version\s*=\s*"([0-9]+(\.[0-9]+){0,3})"') { throw 'cannot read the host version' }
$version = $Matches[1]

$out = Join-Path $root 'dist\extension'
if (Test-Path $out) { Remove-Item $out -Recurse -Force }
New-Item -ItemType Directory -Force $out | Out-Null
# everything the browser needs, nothing else (no tests, no node package file)
$src = Join-Path $root 'extension'
Get-ChildItem $src -Recurse -File | Where-Object { $_.FullName -notmatch '\\test\\' -and $_.Name -ne 'package.json' } | ForEach-Object {
  $rel = $_.FullName.Substring($src.Length + 1)
  $dest = Join-Path $out $rel
  New-Item -ItemType Directory -Force (Split-Path $dest) | Out-Null
  Copy-Item $_.FullName $dest
}

$utf8 = New-Object Text.UTF8Encoding($false)
$msgs = Join-Path $out '_locales\en\messages.json'
[IO.File]::WriteAllText($msgs, ([IO.File]::ReadAllText($msgs) -replace 'BRAND_NAME', $name), $utf8)

$brandJs = "// Generated by scripts/package-extension.ps1 from brand/brand.toml.`nexport const BRAND_NAME = '$($name -replace "'", "\'")';`nexport const HOST = 'com.$product.host';`n"
[IO.File]::WriteAllText((Join-Path $out 'brand.js'), $brandJs, $utf8)

$mf = Join-Path $out 'manifest.json'
$m = [IO.File]::ReadAllText($mf) | ConvertFrom-Json
$m.version = $version
[IO.File]::WriteAllText($mf, ($m | ConvertTo-Json -Depth 8), $utf8)

Write-Host "extension $version for '$name' (host com.$product.host) -> $out"
